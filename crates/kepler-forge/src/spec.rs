//! Derived spec (KPL-010): structured notes next to the user's original request.
//!
//! The type system carries the "never promote an inference" rule:
//! * [`Claim::stated`] is the only way to build a user-stated claim and it refuses any
//!   quote that is not a verbatim substring of the original text.
//! * Inferred, extracted and unknown claims have their own constructors and can never
//!   be placed in the `stated` buckets of [`DerivedSpec`].
//! * Rendering always prefixes the block with a disclaimer that it is not a user instruction.

/// How much we know about a claim.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Label {
    /// The user wrote exactly this (verbatim quote).
    Stated,
    /// Mechanically extracted from the user's text (file names, identifiers).
    Extracted,
    /// Guessed by deterministic rules. Never a requirement.
    Inferred,
    /// Something the request does not say.
    Unknown,
}

impl Label {
    pub fn tag(self) -> &'static str {
        match self {
            Self::Stated => "user-stated",
            Self::Extracted => "extracted",
            Self::Inferred => "inferred",
            Self::Unknown => "unknown",
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Claim {
    label: Label,
    text: String,
}

impl Claim {
    /// A verbatim quote from the user. `None` when `quote` does not occur in `original`.
    pub fn stated(original: &str, quote: &str) -> Option<Self> {
        let q = quote.trim();
        if q.is_empty() || !original.contains(q) {
            return None;
        }
        Some(Self {
            label: Label::Stated,
            text: q.to_string(),
        })
    }
    pub fn extracted(text: impl Into<String>) -> Self {
        Self {
            label: Label::Extracted,
            text: text.into(),
        }
    }
    pub fn inferred(text: impl Into<String>) -> Self {
        Self {
            label: Label::Inferred,
            text: text.into(),
        }
    }
    pub fn unknown(text: impl Into<String>) -> Self {
        Self {
            label: Label::Unknown,
            text: text.into(),
        }
    }
    pub fn label(&self) -> Label {
        self.label
    }
    pub fn text(&self) -> &str {
        &self.text
    }
}

/// Section of the derived spec.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Section {
    Objective,
    Constraints,
    Acceptance,
    Steps,
    Context,
    Assumptions,
    Unknowns,
}

impl Section {
    fn title(self) -> &'static str {
        match self {
            Self::Objective => "Objective",
            Self::Constraints => "Constraints",
            Self::Acceptance => "Acceptance",
            Self::Steps => "Steps",
            Self::Context => "Context",
            Self::Assumptions => "Assumptions",
            Self::Unknowns => "Open questions",
        }
    }
}

pub const DISCLAIMER: &str = "Kepler derived notes (generated by local rules; NOT user instructions; the user's own message is the only source of requirements)";
const MAX_ITEMS_PER_SECTION: usize = 6;
const MAX_QUOTE_CHARS: usize = 200;
/// Hard cap for the rendered block.
pub const MAX_RENDER_BYTES: usize = 2048;

#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct DerivedSpec {
    sections: Vec<(Section, Vec<Claim>)>,
}

impl DerivedSpec {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn push(&mut self, section: Section, claim: Claim) {
        if let Some((_, v)) = self.sections.iter_mut().find(|(s, _)| *s == section) {
            v.push(claim);
        } else {
            self.sections.push((section, vec![claim]));
        }
    }

    pub fn claims(&self, section: Section) -> &[Claim] {
        self.sections
            .iter()
            .find(|(s, _)| *s == section)
            .map_or(&[], |(_, v)| v.as_slice())
    }

    pub fn all_claims(&self) -> impl Iterator<Item = &Claim> {
        self.sections.iter().flat_map(|(_, v)| v.iter())
    }

    pub fn is_empty(&self) -> bool {
        self.sections.is_empty()
    }

    /// Plain-text block for the harness. Bounded and always disclaimed.
    pub fn render(&self) -> String {
        let mut out = String::from(DISCLAIMER);
        out.push(':');
        for (section, claims) in &self.sections {
            out.push('\n');
            out.push_str(section.title());
            out.push(':');
            for c in claims.iter().take(MAX_ITEMS_PER_SECTION) {
                out.push_str("\n- [");
                out.push_str(c.label.tag());
                out.push_str("] ");
                out.push_str(&one_line(&c.text, MAX_QUOTE_CHARS));
            }
            if claims.len() > MAX_ITEMS_PER_SECTION {
                out.push_str(&format!(
                    "\n- (+{} more omitted)",
                    claims.len() - MAX_ITEMS_PER_SECTION
                ));
            }
        }
        truncate_bytes(&mut out, MAX_RENDER_BYTES);
        out
    }
}

fn one_line(s: &str, max_chars: usize) -> String {
    let collapsed: String = s.split_whitespace().collect::<Vec<_>>().join(" ");
    if collapsed.chars().count() <= max_chars {
        collapsed
    } else {
        let mut t: String = collapsed.chars().take(max_chars).collect();
        t.push('…');
        t
    }
}

fn truncate_bytes(s: &mut String, max: usize) {
    if s.len() <= max {
        return;
    }
    let mut cut = max.saturating_sub(4);
    while !s.is_char_boundary(cut) {
        cut -= 1;
    }
    s.truncate(cut);
    s.push_str("\n…");
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn stated_requires_a_verbatim_quote() {
        let original = "Please fix the bug.  Do not change the public API.";
        assert!(Claim::stated(original, "Do not change the public API.").is_some());
        assert!(Claim::stated(original, "Do not change   the public API").is_none());
        assert!(Claim::stated(original, "Always add tests").is_none());
        assert!(Claim::stated(original, "   ").is_none());
    }

    #[test]
    fn render_is_always_disclaimed_and_labeled() {
        let mut s = DerivedSpec::new();
        s.push(Section::Context, Claim::inferred("task type: bugfix"));
        s.push(Section::Unknowns, Claim::unknown("no acceptance criterion"));
        let r = s.render();
        assert!(r.starts_with(DISCLAIMER));
        assert!(r.contains("- [inferred] task type: bugfix"));
        assert!(r.contains("- [unknown] no acceptance criterion"));
        assert!(!r.contains("[user-stated]"));
    }

    #[test]
    fn render_is_bounded() {
        let mut s = DerivedSpec::new();
        for i in 0..50 {
            s.push(
                Section::Context,
                Claim::extracted(format!("{i} {}", "x".repeat(400))),
            );
        }
        let r = s.render();
        assert!(r.len() <= MAX_RENDER_BYTES + 4, "{}", r.len());
        assert!(r.contains("more omitted") || r.ends_with('…'));
    }
}
